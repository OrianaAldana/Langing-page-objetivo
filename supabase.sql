-- Objetivo: única tabla para inscripciones a la beta (FN0).
-- Ejecutar en Supabase > SQL Editor.
create table if not exists public.inscritos_beta (
  id bigint generated by default as identity primary key,
  nombre text not null check (char_length(trim(nombre)) >= 2),
  correo text not null unique check (char_length(correo) <= 254),
  perfil text not null check (perfil in ('Estudiante', 'Profesional', 'Emprendedor/a', 'Otro')),
  necesidad text not null check (char_length(trim(necesidad)) >= 8),
  interes text not null check (interes in ('Planificar metas', 'Calcular ahorro', 'Organizar tareas', 'Ver progreso')),
  fecha_inscripcion timestamptz not null default now()
);

alter table public.inscritos_beta enable row level security;

-- Elimina políticas anteriores con los mismos nombres si se vuelve a ejecutar.
drop policy if exists "Public can register beta interest" on public.inscritos_beta;
drop policy if exists "No public reads" on public.inscritos_beta;

-- Solo permite INSERT anónimo; no se concede SELECT público.
create policy "Public can register beta interest"
on public.inscritos_beta
for insert
to anon
with check (
  char_length(trim(nombre)) >= 2
  and char_length(trim(necesidad)) >= 8
  and perfil in ('Estudiante', 'Profesional', 'Emprendedor/a', 'Otro')
  and interes in ('Planificar metas', 'Calcular ahorro', 'Organizar tareas', 'Ver progreso')
);

-- Nota: al no crear política SELECT para anon, los visitantes no pueden leer
-- las inscripciones mediante la API. El acceso administrativo se hace desde
-- el panel protegido de Supabase. No exponer service_role en el frontend.
grant insert on public.inscritos_beta to anon;
grant usage, select on sequence public.inscritos_beta_id_seq to anon;
